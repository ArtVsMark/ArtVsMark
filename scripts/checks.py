"""Свёртка записей check-runs по имени — в одном месте на весь репозиторий.

Зачем отдельный модуль ради десяти строк. Правило каталога 009 говорит: считать
уникальные имена, а не записи. Оно было известно, помечено в `.rules/bindings.json`
как действующее — и всё равно нарушено в новом коде: сборка метрик сворачивала
записи правильно, а конвейер слияния, написанный позже, сравнивал исход каждой
записи и считал незелёным PR, у которого рядом со свежей успешной проверкой
висела отменённая.

Знание правила не помогло, потому что механизма не было: свёртка жила
выражением внутри функции, и второй потребитель написал своё. Это 090 —
общая утилита выносится **выше обеих** подсистем, и выносится до появления
второго потребителя, а не после третьего.

GitHub отдаёт по одному имени столько записей, сколько раз проверка
запускалась: отмена предыдущего прогона при новом пуше, повтор после
обновления ветки, ручной перезапуск. История событий, а не текущее состояние.
"""

from __future__ import annotations

# Исходы, которые не мешают слиянию. `None` сюда не входит намеренно: пустой
# исход означает «ещё идёт», а не «прошло».
GOOD = ("success", "skipped", "neutral")


def latest_by_name(runs: list[dict]) -> dict[str, dict]:
    """Самая свежая запись на каждое имя проверки.

    Свежесть — по времени старта, при совпадении — по идентификатору: он
    растёт монотонно, и это единственный тай-брейк, который не зависит от
    точности часов площадки.
    """
    latest: dict[str, dict] = {}
    for run in sorted(runs, key=lambda r: (r.get("started_at") or "", r.get("id") or 0)):
        latest[run["name"]] = run
    return latest


def unique_names(runs: list[dict]) -> set[str]:
    """Имена проверок без повторов — «сколько проверок на этом коммите»."""
    return {run["name"] for run in runs}


def red_names(runs: list[dict]) -> list[str]:
    """Имена проверок, чья свежая запись не зелёная.

    Пустой список означает «все свежие записи зелёные» — и **не** означает
    «проверки были»: пустой вход тоже даёт пустой выход, поэтому наличие
    проверок вызывающий проверяет отдельно.
    """
    return sorted(name for name, run in latest_by_name(runs).items() if run.get("conclusion") not in GOOD)
