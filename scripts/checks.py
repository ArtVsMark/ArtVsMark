"""Свёртка записей check-runs по имени — в одном месте на весь репозиторий.

Зачем отдельный модуль ради нескольких строк. Правило каталога 009 говорит:
считать уникальные имена, а не записи. Оно было известно, помечено в
`.rules/bindings.json` как действующее — и всё равно нарушено в новом коде:
сборка метрик сворачивала записи правильно, а конвейер слияния, написанный
позже, сравнивал исход каждой записи и считал незелёным PR, у которого рядом со
свежей успешной проверкой висела отменённая.

Знание правила не помогло, потому что механизма не было: свёртка жила
выражением внутри функции, и второй потребитель написал своё. Это 090 —
общая утилита выносится **выше обеих** подсистем.

GitHub отдаёт по одному имени столько записей, сколько раз проверка
запускалась: отмена предыдущего прогона при новом пуше, повтор после
обновления ветки, ручной перезапуск. История событий, а не текущее состояние.

**Потребитель остался один.** Второй — собственный конвейер слияния — исчез
вместе со скриптом: слияние отдано штатному автомержу площадки, и «зелено ли
здесь» решает теперь она, по обязательным проверкам защиты ветки. Вместе с ним
ушли и функции, отвечавшие на этот вопрос: `latest_by_name` и `red_names`. Их
знание — «свежая запись, а бегущая не считается зелёной» — записано в
`HISTORY.md` и в правиле 009, а код, который никто не зовёт и ничто не
проверяет, хуже отсутствующего.

Модуль при этом остался, хотя потребитель один: правило про уникальные имена
стоило витрине неверной цифры на странице, и место, где оно названо по имени,
дороже трёх строк экономии.

Запуск::  python scripts/checks.py --selftest
Исходы: 0 — чисто; 1 — самопроверка провалена; 2 — запустить не удалось
(модуль не разобрался — это видно трассировкой импорта, а не кодом).
"""

from __future__ import annotations

import os
import re
import subprocess
import sys


def git_paths(*args: str, cwd=None) -> list[str]:
    """Пути из git, прочитанные по NUL, а не по строкам.

    БЕЗ ``-z`` git ЭКРАНИРУЕТ имена с не-ASCII символами и пробелами: заключает
    в кавычки и выводит байты восьмеричными последовательностями. Построенный из
    такой строки путь не разрешается, и файл молча выпадает из обработки —
    проверка остаётся зелёной, ничего не увидев.

    Воспроизведено на подделанном дереве: три файла в ``assets/`` —
    ``normal-dark.svg``, ``утечка-dark.svg`` и ``с пробелом.svg``. Разбор по
    строкам с фильтром ``endswith(".svg")`` увидел ОДИН: у остальных строка
    кончается кавычкой, а не расширением. ``.split()`` в разборе диапазона был
    хуже вдвое — он рвал по пробелам и путь с пробелом превращал в два.

    ПОМОЩНИК ОБЩИЙ, А НЕ ТРИ КОПИИ (правило 090): пути из git читают гейт ролей,
    гейт журнала и сверка производного, и разъехались бы они молча — первый же
    исправленный оставил бы два слепых.

    Возвращает список путей. Сколько их — печатает вызывающий: без числа
    слепота проверки неотличима от чистого результата (правило 165).
    """
    command = ["git"]
    if cwd is not None:
        command += ["-C", str(cwd)]
    out = subprocess.run([*command, *args, "-z"], capture_output=True,
                         text=True, encoding="utf-8", check=True).stdout
    return [path for path in out.split("\0") if path]


#: Уровни площадки. Список закрытый: команда с чужим словом площадкой
#: игнорируется молча, и находка не доехала бы никуда.
LEVELS = ("error", "warning", "notice")


#: Строка хвостового блока: `Ключ: значение`. Ключ без пробелов — так его
#: разбирает и сам git, и разбор каталога.
TRAILER_LINE = re.compile(r"^([A-Za-z][A-Za-z0-9-]*):\s*(.+?)\s*$")


def trailers(body: str) -> dict[str, list[str]]:
    """Трейлеры сообщения — из ХВОСТОВОГО блока, а не из любой строки.

    Правило каталога 156, и оно оплачено дважды. У каталога гейт атрибуции
    отверг изменение витрины #95, найдя соавтора «github-actions[bot] в
    уплотнённый коммит. #83 сделал автором»: слово `Co-authored-by` стояло в
    ПРОЗЕ и после переноса строки оказалось первым в ней. Такого соавтора не
    существует — это середина фразы.

    Цена ошибки несимметрична: разбор по образцу «строка начинается с имени»
    отвергает изменение тем охотнее, чем добросовестнее описан предмет.

    Хвостовой блок — последний абзац, у которого **все** непустые строки имеют
    форму `Ключ: значение`. Абзац, где хоть одна строка прозаическая, блоком не
    считается целиком: иначе разбор снова начинает угадывать.

    Помощник живёт здесь, а не в двух гейтах: тот же приём нужен и проверке
    авторства коммитов, и решению о стоп-кране, и вторая копия разошлась бы с
    первой молча (правило 090).
    """
    paragraphs = [block for block in re.split(r"\n\s*\n", body or "") if block.strip()]
    if not paragraphs:
        return {}
    lines = [line for line in paragraphs[-1].split("\n") if line.strip()]
    parsed = [TRAILER_LINE.match(line) for line in lines]
    if not all(parsed):
        return {}
    found: dict[str, list[str]] = {}
    for match in parsed:
        found.setdefault(match.group(1).lower(), []).append(match.group(2))
    return found


def annotate(level: str, text: str) -> str:
    """Строка находки — командой площадки в прогоне, обычной строкой вне его.

    ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ В КАЖДОМ ГЕЙТЕ. Замер правила 151: окну витрины логи
    прогонов закрыты — ``GET /actions/runs/<id>/logs`` уходит на хранилище,
    куда прокси отвечает отказом. До окна доходят исход каждого шага и
    аннотации check-run, а аннотация появляется только у того, что напечатано
    командой площадки. Гейт, печатающий причину в обычный поток, на чужом
    красном оставляет ровно «Process completed with exit code 1».

    ПОЧЕМУ НЕ ВСЕГДА С ПРЕФИКСОМ. Вне прогона ``::error::`` — шум перед
    сообщением, которое человек и так читает. Признак берётся у площадки
    (``GITHUB_ACTIONS``), а не выводится из наличия токена: токен бывает и на
    машине разработчика.

    Помощник вынесен ВЫШЕ гейтов, а не скопирован в каждый (правило 090): у
    восьми копий разъехался бы формат, и молча — площадка не жалуется на
    команду, которой не знает, она её просто не показывает.
    """
    if level not in LEVELS:
        raise ValueError(f"уровень {level!r} вне набора {LEVELS}")
    prefix = f"::{level}::" if os.environ.get("GITHUB_ACTIONS") == "true" else ""
    return f"{prefix}{text}"


def selftest() -> int:
    """Обе ветки ``annotate`` и отказ на чужом уровне (правила 140, 145).

    Набор ЗОВЁТ механизм и смотрит на его ответ, а не повторяет условие
    «если GITHUB_ACTIONS, то префикс» (правило 150): при смене признака
    случаи продолжат спрашивать функцию.
    """
    broken = []

    # ── хвостовой блок, а не любая строка (правило 156) ────────────────────
    # Обе ошибки названы: принять прозу за трейлер значит отвергнуть верное
    # изменение тем охотнее, чем подробнее оно описано; не увидеть настоящий
    # трейлер — пропустить коммит без атрибуции в общую ветку.
    TAIL = "Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>"
    trailer_cases = [
        ("хвост из одного трейлера", f"Разбор.\n\n{TAIL}", ["co-authored-by"]),
        ("хвост из двух", f"Тело.\n\n{TAIL}\nClaude-Session: https://x", ["claude-session", "co-authored-by"]),
        ("слово в прозе — не трейлер",
         "площадка дописывает\nCo-Authored-By: github-actions[bot] в уплотнённый коммит", []),
        ("проза внутри хвостового абзаца отменяет весь блок",
         f"Тело.\n\n{TAIL}\nи ещё пояснение", []),
        ("трейлер в середине сообщения не считается",
         f"Начало.\n\n{TAIL}\n\nПродолжение прозой.", []),
        ("тела нет вовсе", "", []),
        ("одни пустые строки", "\n\n   \n", []),
        ("регистр ключа не важен", "Тело.\n\nco-authored-by: A <a@b>", ["co-authored-by"]),
        ("двоеточия нет — не трейлер", "Тело.\n\nCo-Authored-By A <a@b>", []),
    ]
    for name, body, expected in trailer_cases:
        got = sorted(trailers(body))
        if got != sorted(expected):
            broken.append(f"трейлеры, {name}: ожидалось {sorted(expected)}, вышло {got}")
        print(f"  {str(got) if got else 'пусто':<34} — трейлеры: {name}")

    # Значение доезжает целиком: по нему сверяют имя со списком согласованных.
    value = trailers(f"Тело.\n\n{TAIL}").get("co-authored-by", [""])[0]
    if value != "Claude Opus 5 <noreply@anthropic.com>":
        broken.append(f"трейлеры: значение обрезано или искажено — {value!r}")

    saved = os.environ.get("GITHUB_ACTIONS")
    try:
        os.environ.pop("GITHUB_ACTIONS", None)
        if annotate("error", "находка") != "находка":
            broken.append("вне прогона строка обросла префиксом — шум человеку")
        os.environ["GITHUB_ACTIONS"] = "true"
        for level in LEVELS:
            got = annotate(level, "находка")
            if got != f"::{level}::находка":
                broken.append(f"в прогоне уровень {level} даёт {got!r}")
        # Признак берётся у площадки дословно: «1» это не «true», и принять
        # его значило бы печатать команду там, где её никто не прочитает.
        os.environ["GITHUB_ACTIONS"] = "1"
        if annotate("error", "находка") != "находка":
            broken.append("чужое значение признака принято за прогон")
    finally:
        os.environ.pop("GITHUB_ACTIONS", None)
        if saved is not None:
            os.environ["GITHUB_ACTIONS"] = saved

    try:
        annotate("fatal", "находка")
    except ValueError:
        pass
    else:
        broken.append("чужой уровень принят — площадка проглотит команду молча")

    for line in broken:
        print(f"  {line}")
    print("  свёртка имён и разметка находок проверены" if not broken else "")
    return 1 if broken else 0


def main() -> int:
    if "--selftest" in sys.argv[1:]:
        return selftest()
    print(__doc__)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
