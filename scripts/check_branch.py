#!/usr/bin/env python3
"""Имя ветки называет ЗАДАЧУ, а не окно, которое её делало.

ЗАЧЕМ. Три соседних проекта из четырёх ведут работу на ветках вида
``agent/<слаг задачи>``: имя говорит, о чём изменение, и ветка живёт ровно
столько, сколько задача. Витрина и глоссарий выбивались — у них имя приходило
из стартовой инструкции окна (``claude/profile-showcase-window-c1vnxz``), то
есть называло ИСПОЛНИТЕЛЯ и его сессию.

ЦЕНА НЕ В КРАСОТЕ ИМЕНИ. Ветка на окно живёт неделю и собирает всё, что окно
успело сделать. Замер на витрине: изменение #129 приехало с пятью коммитами о
пяти разных предметах — контракт фактов, показатели соседей, чужой пакет, две
починки гейтов, — и оговорка «пересечение файлов сильнее темы» из свода
прикрывала это задним числом. Ветка на задачу такой возможности не даёт: тема
кончилась — ветка кончилась.

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ. Он не проверяет, что в изменении ОДНА
тема: судить о единстве темы машине нечем, и в своде это названо прямо (правило
057). Он держит половину, которая следует из данных, — что имя названо по
задаче (правило 182). Ветка `agent/rules` тоже может привезти пять тем; но
ветка, названная по окну, привезёт их обязательно.

ПОЧЕМУ ЭТО НЕ «ПЕРЕКЛЮЧАТЕЛЬ ПО ИМЕНИ ВЕТКИ». Правило 147 запрещает менять
ПОВЕДЕНИЕ конвейера по имени: прогон, который молча не сработал на ветке с
«не тем» именем, отменяет операцию без следа. Здесь наоборот — поведение
одинаково для всех веток, а имя вызывает ГРОМКИЙ отказ с причиной. Открытие
изменения по-прежнему идёт с любой рабочей ветки (``branches-ignore``).

ВЕТКИ ПРОГОНОВ — НЕ ПРЕДМЕТ. Суточная сборка открывает изменение с
``chore/metrics``: у неё нет задачи, есть расписание, и требовать от машины
слаг задачи значило бы требовать невозможного (правило 051).

Запуск::  python scripts/check_branch.py <имя-ветки>
Исходы: 0 — имя годится; 1 — имя называет не задачу; 2 — проверка не
отработала (имени не передали).
"""

from __future__ import annotations

import sys

import checks

#: Приставка рабочей ветки. Общая с соседями — грейдером, каталогом правил и
#: Claude-Code_Usage-Token: одно соглашение на четыре проекта дешевле четырёх.
PREFIX = "agent/"

#: Ветки, которые открывают ПРОГОНЫ. У них нет задачи, и слага быть не может.
MACHINE = ("chore/metrics",)

# ГЕЙТ ДЕРЖИТ ПРИСТАВКУ И НЕПУСТОЙ СЛАГ — И БОЛЬШЕ НИЧЕГО. Две попытки судить
# сам слаг отвергли собственную ветку этого изменения, обе на первом прогоне:
#
#   * запрет на слова «window», «session», «окно» отказал ветке
#     `agent/branch-names-a-task-not-a-window`. Слаг говорил О ПРЕДМЕТЕ, а не
#     называл окно, и по вхождению одно от другого не отличается — тот же
#     класс, что «упоминание в комментарии — не обращение» у audit_calls;
#   * образец «хвост сессии» — шесть-восемь знаков в конце — принял за хвост
#     слово `window`. Настоящие хвосты выглядят как `c1vnxz`, `beg7bm`,
#     `dthzio`: у первых двух есть цифра, у третьего нет ни цифры, ни
#     повторяющегося признака вообще. Различить хвост и слово из шести букв
#     нечем.
#
# Обе догадки убраны, а не подправлены: гейт, который приходится обходить
# переименованием законной ветки, приучает не доверять гейтам (051).
#
# ЧТО ОСТАЛОСЬ НЕПРОВЕРЯЕМЫМ И НАЗВАНО (правило 057): ветка `agent/что-то`
# может быть названа по окну — приставка этого не различает. Держится это
# сводом и решением владельца, а не машиной.


def verdict(branch: str) -> str:
    """Претензия к имени ветки, либо пустая строка.

    Вынесено из ``main``, чтобы набор ЗВАЛ проверку, а не повторял её условие
    (правило 150).
    """
    if branch in MACHINE:
        return ""
    if not branch.startswith(PREFIX):
        return (f"ветка {branch!r} не начинается с {PREFIX!r}. Имя ветки называет "
                f"ЗАДАЧУ — так же, как у грейдера, каталога правил и "
                f"Claude-Code_Usage-Token; одно соглашение на четыре проекта дешевле "
                f"четырёх")
    slug = branch[len(PREFIX):]
    if not slug:
        return f"ветка {branch!r} — приставка без слага: имя не называет ничего"
    return ""


def selftest() -> int:
    """Обе стороны: имя годное и имя, названное по окну.

    Ложный отказ здесь дороже пропуска — он остановил бы изменение из-за
    имени ветки, то есть из-за того, что чинится переименованием, а не кодом.
    Поэтому набор разбирает и служебные ветки, и слаги, случайно похожие на
    хвост сессии.
    """
    cases = [
        ("слаг задачи", "agent/branch-names-a-task-not-a-window", False),
        ("слаг с номером задачи", "agent/61-neighbour-facts", False),
        ("ветка прогона — не предмет", "chore/metrics", False),
        ("без приставки", "fix/coverage", True),
        ("приставка без слага", "agent/", True),
        ("имя окна", "claude/profile-showcase-window-c1vnxz", True),
        # Слаг ВПРАВЕ говорить об окне: эта ветка так и называется. Запрет по
        # слову отверг бы её — и отверг на первом прогоне.
        ("слаг про окна — законный слаг", "agent/branch-names-a-task-not-a-window", False),
        # Хвост сессии при верной приставке гейт НЕ ловит, и это названо: он
        # неотличим от слова той же длины. Случай оставлен в наборе, чтобы
        # граница была видна, а не подразумевалась.
        ("хвост сессии при верной приставке гейту не виден", "agent/rules-c1vnxz", False),
        ("обычный слаг из двух слов", "agent/rules-inbox", False),
    ]
    broken = []
    for name, branch, must_reject in cases:
        said = verdict(branch)
        if bool(said) is not must_reject:
            broken.append(f"{name}: ожидалось {'отказ' if must_reject else 'пропуск'} "
                          f"на {branch!r}, вышло {said!r}")
        print(f"  {'отвергнута' if said else 'принята  '} — {branch}")

    # Отказ обязан НАЗЫВАТЬ ветку: «имя не годится» без имени — отказ, по
    # которому нечего чинить (правило 083).
    if "claude/x-ab12cd" not in verdict("claude/x-ab12cd"):
        broken.append("отказ не называет ветку, из-за которой он вынесен")

    if broken:
        print("\nсамопроверка провалена:", file=sys.stderr)
        for line in broken:
            print(f"  {line}", file=sys.stderr)
        return 1
    print("самопроверка пройдена: гейт отвергает имя окна и пропускает имя задачи")
    return 0


def main() -> int:
    argv = sys.argv[1:]
    if "--selftest" in argv:
        return selftest()

    branch = next((a for a in argv if not a.startswith("-")), "")
    if not branch:
        # Третий исход: проверке не с чем работать. Чинит это тот, кто её
        # запускает, а не автор изменения (правило 039).
        print(checks.annotate("error", "проверка не отработала: имя ветки не передано"),
              file=sys.stderr)
        return 2

    said = verdict(branch)
    if said:
        print(checks.annotate("error", f"имя ветки называет не задачу: {said}"),
              file=sys.stderr)
        print("\n  Переименуйте ветку и откройте изменение заново: имя ветки —"
              "\n  первое, что читают в списке изменений, и оно обязано говорить,"
              "\n  О ЧЁМ работа, а не кто её делал.", file=sys.stderr)
        return 1

    print(f"имя ветки называет задачу: {branch}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
