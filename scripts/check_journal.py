#!/usr/bin/env python3
"""Правка поведения приезжает вместе с записью в журнале.

ЗАЧЕМ. Правило 138: журнал пополняется тем же заходом, что и правка, а не перед
выпуском. У витрины это единственная память о решениях — фрагментов, как у
грейдера, здесь нет, и запись, отложенная «на потом», не пишется никогда.

ЗАМЕР, А НЕ ОПАСЕНИЕ. По 71 первопредку общей ветки: 30 изменений правили
поведение, и 3 из них приехали без строки в журнале. Одно — настоящее решение на
48 строк в прогоне очереди правил (#53), где отложенная запись означает, что
следующее окно будет разбирать тот же вопрос заново. Правило нарушалось в
каждом десятом изменении, и держалось оно абзацем свода.

ПОЧЕМУ ОТКАЗ, А НЕ ПРЕДУПРЕЖДЕНИЕ. Предупреждение здесь равно молчанию: оно
адресовано тому же окну, которое только что решило не писать. Но отказ обязан
иметь выход, иначе его начнут обходить пустой строкой в журнале — что хуже
отсутствия записи, потому что выглядит как память.

ВЫХОД НАЗЫВАЕТСЯ ВСЛУХ. Строка ``Журнал: не требуется — <причина>`` в сообщении
любого коммита диапазона снимает требование. Это осознанный жест, он остаётся в
истории и читается — в отличие от решения не писать, которое не остаётся нигде.
Пустая причина жестом не считается: «не требуется» без «почему» — это то же
молчание, только подписанное.

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Он не судит, ЧТО написано в журнале, — только что запись
пришла тем же заходом. Отличить решение от опечатки в комментарии машина не
может, и обе стороны этой границы названы: правка поведения без записи
отвергается, содержание записи остаётся на авторе (правило 146).

Запуск::  python scripts/check_journal.py [origin/main..HEAD]
Исходы: 0 — чисто; 1 — правка поведения без записи; 2 — проверка не отработала.
"""

from __future__ import annotations

import re
import subprocess
import sys

import checks

#: Что считается правкой поведения. Список короткий намеренно: `.rules/` сюда не
#: входит — ответ каталогу меняется и от чужой правки, а `README.md` собирается
#: сборкой, и требовать журнал от машинной правки значило бы требовать его от
#: расписания.
BEHAVIOUR = (re.compile(r"^scripts/.*\.py$"), re.compile(r"^\.github/workflows/.*\.ya?ml$"))
JOURNAL = "HISTORY.md"

#: Осознанный отказ от записи — с причиной, которая остаётся в истории.
WAIVER = re.compile(r"^Журнал:\s*не требуется\s*[—-]\s*(?P<why>\S.*)$", re.M)


def touched(paths: list[str]) -> list[str]:
    """Файлы поведения среди изменённых."""
    return [p for p in paths if any(rx.match(p) for rx in BEHAVIOUR)]


def audit(paths: list[str], messages: str, authors: list[str] | None = None) -> tuple[list[str], str]:
    """Претензия к заходу и причина осознанного отказа, если она названа.

    ЧТО ДЕЛАЕТ ТРЕТИЙ ДОВОД. Гейт требует запись о РЕШЕНИИ, а машина решений не
    принимает: dependabot поднял SHA-пин чужого действия в pr-check.yml — по
    списку BEHAVIOUR это правка поведения, и изменение #134 встало намертво.
    Записать в журнал было нечего, а строку освобождения писать некому: бот её
    не напишет, человек в чужое изменение не допишет — оно перезаписывается
    следующим прогоном бота.

    Освобождение даётся по АВТОРУ, а не по имени ветки: имя бот выбирает сам и
    может сменить формат, учётная запись площадки устойчива. Список
    освобождённых закрыт и лежит в scripts/checks.py::MACHINE_AUTHORS — это
    признание «требовать нечего», а не «боту можно» (правило 051).

    Довод односторонний: хоть один живой автор в диапазоне — журнал требуется
    со всех. Иначе бот, подмешавшийся в человеческий заход, освободил бы его.

    Вынесено из ``main``, чтобы проверять на подставных наборах, не ходя в git.
    """
    waiver = WAIVER.search(messages)
    behaviour = touched(paths)
    if not behaviour:
        return [], ""
    if JOURNAL in paths:
        return [], ""
    if waiver:
        return [], waiver.group("why").strip()
    if authors and all(checks.machine_made(a) for a in authors):
        return [], "правку сделала машина: решения она не принимает, записывать нечего"
    return [f"поведение правится без записи в журнале: "
            f"{checks.tail(behaviour, 5)}"], ""


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], capture_output=True, text=True, encoding="utf-8",
                          check=True).stdout


def selftest() -> int:
    """Прогоняет через гейт то, что он обязан отвергнуть и обязан пропустить.

    Набор двусторонний (правило 140). Ложный отказ дороже пропуска: гейт,
    требующий журнал от правки, которая ничего не решает, приучит писать в
    журнал пустое — а пустая запись хуже отсутствующей, потому что выглядит
    как память.
    """
    cases = [
        ("правка скрипта с записью", ["scripts/a.py", "HISTORY.md"], "", False),
        ("правка прогона с записью", [".github/workflows/a.yml", "HISTORY.md"], "", False),
        ("правка скрипта без записи", ["scripts/a.py"], "", True),
        ("правка прогона без записи", [".github/workflows/a.yml"], "", True),
        ("оба вида сразу без записи", ["scripts/a.py", ".github/workflows/a.yml"], "", True),
        ("документация без записи — не предмет", ["README.md", ".rules/roles.md"], "", False),
        ("ответ каталогу без записи — не предмет", [".rules/bindings.json"], "", False),
        ("дифф не прочитан", [], "", False),
        ("осознанный отказ с причиной",
         ["scripts/a.py"], "fix: чинит опечатку\n\nЖурнал: не требуется — правка опечатки в комментарии", False),
        ("отказ без причины жестом не считается",
         ["scripts/a.py"], "fix: что-то\n\nЖурнал: не требуется —", True),
        ("отказ без тире жестом не считается",
         ["scripts/a.py"], "fix: что-то\n\nЖурнал: не требуется", True),
        ("слово в прозе отказом не считается",
         ["scripts/a.py"], "fix: тут сказано, что журнал не требуется вообще", True),
    ]
    broken = []
    for name, paths, messages, must_reject in cases:
        found, _ = audit(paths, messages)

    # ── у машины журнала не требуют (правило 051) ─────────────────────────
    # Бот не принимает решений, и записывать ему нечего; строку освобождения
    # тоже писать некому — его изменение перезаписывается следующим прогоном.
    # Обратная сторона важнее: один живой автор в заходе возвращает требование
    # всем, иначе подмешавшийся бот освободил бы человека.
    machine_cases = [
        ("правка бота без записи", ["scripts/a.py"], ["dependabot[bot]"], False),
        ("прогон площадки", [".github/workflows/a.yml"], ["github-actions[bot]"], False),
        ("человек в том же заходе — журнал нужен",
         ["scripts/a.py"], ["dependabot[bot]", "ArtVsMark"], True),
        ("живой автор", ["scripts/a.py"], ["ArtVsMark"], True),
        ("авторов не прочитали — судим как раньше", ["scripts/a.py"], [], True),
    ]
    for name, paths, authors, must_reject in machine_cases:
        found, why = audit(paths, "", authors)
        if bool(found) is not must_reject:
            broken.append(f"машинный заход, {name}: ожидалось "
                          f"{'отказ' if must_reject else 'пропуск'}, вышло {found}")
        # Освобождение обязано НАЗЫВАТЬ себя: молчаливый пропуск неотличим от
        # «предмета не было» (правило 151).
        if not must_reject and not why:
            broken.append(f"машинный заход, {name}: пропуск молчит о причине")
        print(f"  {'отвергнут' if found else 'пропущен '} — машинный заход: {name}")

    for name, paths, messages, must_reject in cases:
        found, _ = audit(paths, messages)
        if bool(found) is not must_reject:
            broken.append(f"{name}: ожидалось {'отказ' if must_reject else 'пропуск'}, вышло {found}")
        print(f"  {'отвергнут' if found else 'пропущен '} — {name}")

    # Отказ обязан НАЗЫВАТЬ предмет: «journal missing» без имени файла — это
    # отказ, по которому нечего чинить (правило 083).
    named, _ = audit(["scripts/build_metrics.py"], "")
    if not any("build_metrics.py" in line for line in named):
        broken.append("отказ не называет файл, из-за которого он вынесен")
    # Причина осознанного отказа обязана доезжать до вызывающего: молча
    # пропустить и молча отвергнуть — одинаково немые исходы (правило 151).
    _, why = audit(["scripts/a.py"], "Журнал: не требуется — сборка переписала сама")
    if why != "сборка переписала сама":
        broken.append(f"причина отказа не доехала: {why!r}")

    if broken:
        print("\nсамопроверка провалена:", file=sys.stderr)
        for line in broken:
            print(f"  {line}", file=sys.stderr)
        return 1
    print("самопроверка пройдена: гейт отвергает то, что обязан, и называет предмет")
    return 0


def main() -> int:
    argv = sys.argv[1:]
    if "--selftest" in argv:
        return selftest()

    rng = next((a for a in argv if not a.startswith("-")), "origin/main..HEAD")
    try:
        base, head = rng.split("..", 1) if ".." in rng else ("origin/main", "HEAD")
        # По NUL, а не по строкам и тем более не `.split()`: тот рвал бы путь с
        # пробелом надвое, а git ещё и экранирует не-ASCII имена (правило 165).
        paths = checks.git_paths("diff", "--name-only", f"{base}...{head}")
        messages = _git("log", "--format=%B", rng)
        # Авторы диапазона: по ним решается, есть ли кому писать журнал.
        authors = [line for line in _git("log", "--format=%an", rng).splitlines() if line.strip()]
    except (subprocess.CalledProcessError, OSError, ValueError) as e:
        # Третий исход: диапазон не разобран — чинит это тот, кто запускает, а
        # не автор изменения (правило 039).
        print(checks.annotate("error", f"проверка не отработала: диапазон {rng!r} "
                              f"не разобран — {e}"), file=sys.stderr)
        return 2

    found, why = audit(paths, messages, authors)
    if found:
        print(checks.annotate("error", f"журнал отстал от правки: {found[0]}"),
              file=sys.stderr)
        print(
            "\n  Решение оседает записью в HISTORY.md тем же заходом, а не перед"
            "\n  выпуском: у витрины это единственная память о том, ПОЧЕМУ так."
            "\n  Если решения здесь нет — скажите это вслух, строкой в сообщении"
            "\n  коммита:\n\n      Журнал: не требуется — <причина>\n"
            "\n  Причина остаётся в истории и читается. Молчание — нет.",
            file=sys.stderr,
        )
        return 1

    if why:
        print(f"журнал не требуется: {why}")
    else:
        print(f"журнал в ногу с правкой: файлов в изменении {len(paths)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
