#!/usr/bin/env python3
"""Отвергает коммит, подписанный контейнерным умолчанием агентского окна.

ПОЧЕМУ ОТДЕЛЬНО ОТ ГЕЙТА АТРИБУЦИИ. Гейт каталога сверяет **трейлеры**:
соавтор вне списка — отказ, след сессии без соавторства — отказ. На **автора**
коммита он не смотрит вовсе, и это проверено прогоном, а не прочитано:

    коммит 4d9e300, автор «Claude <noreply@anthropic.com>» — гейт ПРОПУСКАЕТ
    коммит без единого трейлера                            — гейт ПРОПУСКАЕТ

Предмет здесь другой, поэтому это не вторая копия чужого механизма, а
недостающая половина. Место ей уровнем выше — в том же действии каталога,
параметром; предложено там же. Пока не переехало — живёт тут.

ПОЧЕМУ ПРОВЕРКА УЗКАЯ. Спрашивается ровно одно запрещённое написание, а не
«правильные имена». У владельца есть свои коммиты из веб-интерфейса с его
noreply-адресом, и объявлять их дефектом неверно; список согласованных имён —
предмет гейта атрибуции, а не этого (правило 051: ложный отказ дороже пропуска).

ЛОВИТ ПОЗДНО, И ЭТО НАЗВАНО. Коммит к моменту проверки уже сделан, и починка
означает ``git commit --amend`` или новый коммит поверх. Раньше поймать нечем:
хука в облачном окне нет. Искать несуществующий способ починить «до» не надо.

ВТОРОЙ ПРЕДМЕТ: ТРЕЙЛЕРА НЕТ ВОВСЕ. Гейт каталога на диапазоне изменения
коммиты без атрибуции **считает и печатает числом, но не отвергает** — требует
он их только на первопредках общей ветки, то есть уже ПОСЛЕ слияния. Разница
не теоретическая: 31 августа изменение #97 уехало в `main` без единого
трейлера, зелёное на всех проверках, и красным стал `attribution-history` —
там, где прошлое уже не переписать (правило 114). Планка не поднята, она
перенесена раньше: то, что общая ветка требует после слияния, изменение
обязано нести до него.

Согласованность ИМЕНИ здесь не проверяется — это предмет гейта каталога, и
второй копии списка не заводится (правило 090). Здесь спрашивается наличие.

Исходы: 0 — чисто; 1 — есть находки; 2 — проверка не отработала.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

import checks

#: Умолчание, которое облачный контейнер проставляет в глобальной настройке.
#: Оно попадало в main пять раз, пока соглашение держалось памятью окна.
FORBIDDEN = {"Claude <noreply@anthropic.com>"}

#: Что писать, а не «добавьте атрибуцию»: имя сверяется со списком в
#: .github/authors.txt гейтом каталога, поэтому образец здесь — из него, а не
#: выдуманный. Строка ставится ХВОСТОВЫМ блоком: разбор ищет её началом строки,
#: и упоминание в прозе он принял бы за трейлер (находка на #95).
TRAILER = "Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>"

#: Что делать, а не «почини атрибуцию»: отказ обязан называть команду целиком.
REMEDY = (
    'git config user.name "ArtVsMark" && '
    'git config user.email "arvs.markitanov@gmail.com"'
)


def body_attribution(body: str) -> str:
    """Претензия к телу изменения, если атрибуции в нём нет. Пусто — есть.

    ЗАЧЕМ ТРЕТИЙ ПРЕДМЕТ, ЕСЛИ ДВА УЖЕ ЕСТЬ. Пока площадка склеивает сообщение
    слияния из коммитов ветки (``squash_merge_commit_message =
    COMMIT_MESSAGES``), тело изменения на атрибуцию не влияет: трейлеры едут в
    общую ветку из коммитов. Ровно поэтому они там и ДВОЯТСЯ — по одному на
    коммит ветки плюс свой от площадки: у изменения #129 их шесть.

    Лечится это переключением на ``PR_BODY``, и тогда предмет меняется местами:
    сообщением коммита в общей ветке становится ТЕЛО изменения, а тела окно
    переписывает руками — и в переписанном трейлеров нет. Первое же слияние
    после переключения уехало бы в `main` без атрибуции и покрасило
    ``attribution-history`` там, где прошлое уже не переписать (правило 114).

    Поэтому гейт заводится ДО переключения, а не после: переключатель настроек
    у владельца, и он должен щёлкнуть его в подготовленное место.

    Спрашивается наличие, а не согласованность имени: список согласованных —
    предмет гейта каталога, второй копии здесь не заводится (правило 090).
    """
    found = checks.trailers(body)
    if "co-authored-by" not in found:
        return ("тело изменения не несёт соавторства: после перехода на PR_BODY "
                "именно оно станет сообщением коммита в общей ветке, и слияние "
                "уедет туда без атрибуции")
    if "claude-session" not in found:
        return ("тело изменения не несёт следа сессии: соавтор назван, а откуда он "
                "взялся — нет; в общей ветке это уже не восстановить")
    return ""


def offenders(authors: list[str]) -> list[str]:
    """Подписи из списка запрещённых, встретившиеся среди авторов."""
    return [a for a in authors if a.strip() in FORBIDDEN]


#: Имя трейлера исполнителя. Разбор живёт в scripts/checks.py: тот же приём
#: нужен решению о стоп-кране, и второй копии не заводится (правило 090).
COAUTHOR = "co-authored-by"


def unattributed(records: list[tuple[str, str, str]]) -> list[tuple[str, str]]:
    """Коммиты без трейлера соавтора: ``(хеш, тема)``.

    Слияния не спрашиваются вовсе — их сообщение составляет площадка, а не
    автор; в диапазоне изменения их и не бывает, но условие названо, чтобы
    проверка не начала врать на ветке, куда влили общую.
    """
    return [(sha, subject) for sha, subject, body in records
            if COAUTHOR not in checks.trailers(body)]


def selftest() -> int:
    """Прогоняет через проверку то, что она обязана отвергнуть и пропустить."""
    cases = [
        ("контейнерное умолчание", ["Claude <noreply@anthropic.com>"], True),
        ("оно же среди верных", ["ArtVsMark <arvs.markitanov@gmail.com>",
                                 "Claude <noreply@anthropic.com>"], True),
        ("согласованный автор", ["ArtVsMark <arvs.markitanov@gmail.com>"], False),
        ("владелец из веб-интерфейса",
         ["Artem Markitanov <86671904+ArtVsMark@users.noreply.github.com>"], False),
        ("соавтор-исполнитель автором не притворяется",
         ["Claude Opus 5 <noreply@anthropic.com>"], False),
        ("бот площадки — не предмет этой проверки",
         ["github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>"], False),
        ("коммитов нет", [], False),
    ]
    broken = []
    # ── атрибуция в ТЕЛЕ изменения (готовность к PR_BODY) ────────────────
    # Обе стороны: пропустить тело без трейлеров — потерять атрибуцию в общей
    # ветке после переключения; потребовать их от прозы — приучить дописывать
    # хвост наугад.
    TAIL = ("\n\nCo-Authored-By: Claude Opus 5 <noreply@anthropic.com>"
            "\nClaude-Session: https://claude.ai/code/session_x")
    body_cases = [
        ("тело с полным хвостом", "Разбор." + TAIL, False),
        ("соавтора нет", "Разбор.\n\nClaude-Session: https://x", True),
        ("следа сессии нет",
         "Разбор.\n\nCo-Authored-By: Claude Opus 5 <noreply@anthropic.com>", True),
        ("тело пустое", "", True),
        ("трейлеры в середине, а не хвостом",
         "Начало." + TAIL + "\n\nПродолжение прозой.", True),
        ("слово в прозе трейлером не считается",
         "Здесь сказано Co-Authored-By, но это середина фразы.", True),
    ]
    for name, body, must_reject in body_cases:
        said = body_attribution(body)
        if bool(said) is not must_reject:
            broken.append(f"тело изменения, {name}: ожидалось "
                          f"{'отказ' if must_reject else 'пропуск'}, вышло {said!r}")
        print(f"  {'отвергнуто' if said else 'принято   '} — тело изменения: {name}")

    for name, authors, must_reject in cases:
        found = offenders(authors)
        if bool(found) is not must_reject:
            broken.append(f"{name}: ожидалось {'отказ' if must_reject else 'пропуск'}, вышло наоборот")
        print(f"  {'отвергнут' if found else 'пропущен '} — {name}")

    # ── второй предмет: трейлер исполнителя ────────────────────────────────
    # Обе стороны. Ложный отказ здесь останавливает работу на верном коммите,
    # ложный пропуск — пускает долг в общую ветку, где его уже не переписать.
    tail = "\n\nCo-Authored-By: Claude Opus 5 <noreply@anthropic.com>"
    trailer_cases = [
        ("трейлер в хвосте", [("a1", "правка", tail.strip())], False),
        ("трейлера нет вовсе", [("b2", "правка", "Обычное тело без хвоста.")], True),
        ("тело пустое", [("c3", "правка", "")], True),
        ("другой регистр — тот же трейлер",
         [("d4", "правка", "co-authored-by: Claude Opus 5 <noreply@anthropic.com>")], False),
        ("трейлер после абзаца", [("e5", "правка", "Разбор." + tail)], False),
        ("один из двух коммитов молчит",
         [("f6", "с хвостом", tail.strip()), ("g7", "без хвоста", "тело")], True),
        ("коммитов нет", [], False),
    ]
    for name, records, must_reject in trailer_cases:
        found = unattributed(records)
        if bool(found) is not must_reject:
            broken.append(f"трейлер, {name}: ожидалось "
                          f"{'отказ' if must_reject else 'пропуск'}, вышло {found}")
        print(f"  {'отвергнут' if found else 'пропущен '} — трейлер: {name}")

    # Отказ обязан назвать КАЖДЫЙ молчащий коммит, а не первый: чинить придётся
    # все, а второй заход стоит ещё одного прогона.
    both = unattributed([("f6", "первый", "тело"), ("g7", "второй", "тело")])
    if len(both) != 2:
        broken.append(f"трейлер: названо {len(both)} молчащих коммитов из двух")

    # СЛОВО В ПРОЗЕ БОЛЬШЕ НЕ СЧИТАЕТСЯ ТРЕЙЛЕРОМ. Предложение витрины принято
    # каталогом как правило 156, и разбор переехал на хвостовой блок: абзац, где
    # хоть одна строка прозаическая, блоком не считается целиком. Раньше здесь
    # стоял ложный ПРОПУСК с оговоркой «чинится на той стороне» — теперь это
    # находка, и коммит с упоминанием в прозе честно называется без атрибуции.
    prose = unattributed([("h8", "правка",
                           "площадка дописывает\n"
                           "Co-Authored-By: github-actions[bot] в уплотнённый коммит")])
    if not prose:
        broken.append("трейлер: слово в прозе принято за трейлер — разбор вернулся "
                      "к образцу по строке вместо хвостового блока (156)")
    print(f"  {'отвергнут' if prose else 'ПРОПУЩЕН '} — трейлер: слово в прозе — не трейлер")

    # Третий объявленный исход — «проверка не отработала», код 2. Он был
    # объявлен в докстроке и не прогонялся ни разу: набор проверял `offenders`,
    # то есть только пути 0 и 1. Правило 145 ровно про это — необъявленная
    # ветка обычно не «работает неверно», а НЕ СУЩЕСТВУЕТ, и при чтении это
    # неотличимо. Поэтому исход прогоняется целиком, запуском самого скрипта:
    # проверить его вызовом `offenders` нельзя, он живёт в `main`.
    probe = subprocess.run(
        [sys.executable, __file__, "нет-такой-ветки..HEAD"],
        capture_output=True, text=True, encoding="utf-8",
    )
    if probe.returncode != 2:
        broken.append(
            f"исход «проверка не отработала» дал код {probe.returncode}, а не 2"
        )
    if "не отработала" not in probe.stderr:
        broken.append("исход «проверка не отработала» не называет себя в потоке ошибок")
    print(f"  код {probe.returncode}     — неразобранный диапазон: проверка не отработала")

    if broken:
        print("\nсамопроверка провалена:", file=sys.stderr)
        for line in broken:
            print(f"  {line}", file=sys.stderr)
        return 1
    print("самопроверка пройдена: проверка отвергает то, что обязана, и все три исхода прогнаны")
    return 0


def main() -> int:
    argv = sys.argv[1:]
    if "--selftest" in argv:
        return selftest()

    # ТЕЛО ИЗМЕНЕНИЯ — ОТДЕЛЬНЫЙ ПРЕДМЕТ, И ПРОВЕРЯЕТСЯ ОТДЕЛЬНЫМ ЗАПУСКОМ.
    # Файлом, а не аргументом: тело многострочное и содержит что угодно, включая
    # кавычки и обратные апострофы, — в командной строке оно рано или поздно
    # порвётся о цитирование оболочки.
    body_file = next((a.removeprefix("--body-file=") for a in argv
                      if a.startswith("--body-file=")), "")
    if body_file:
        try:
            body = pathlib.Path(body_file).read_text(encoding="utf-8")
        except OSError as e:
            print(checks.annotate("error", f"проверка не отработала: тело изменения "
                                  f"не прочитано ({body_file}) — {e}"), file=sys.stderr)
            return 2
        said = body_attribution(body)
        if said:
            print(checks.annotate("error", f"атрибуция в теле изменения: {said}"),
                  file=sys.stderr)
            print("\n  Допишите в КОНЕЦ тела хвостовой блок:\n\n"
                  f"      {TRAILER}\n      Claude-Session: <адрес сессии>\n"
                  "\n  Блок обязан быть последним абзацем и состоять только из\n"
                  "  строк «Ключ: значение» — проза внутри него отменяет весь блок.",
                  file=sys.stderr)
            return 1
        print("тело изменения несёт атрибуцию: соавтор и след сессии на месте")
        return 0

    rng = next((a for a in argv if not a.startswith("-")), "origin/main..HEAD")
    try:
        # Тело нужно второму предмету — трейлеру; записи разделяет \x1e,
        # потому что тело многострочное и по строкам его не разобрать.
        out = subprocess.run(
            ["git", "log", "--no-merges", "--format=%an <%ae>%x00%h%x00%s%x00%b%x1e", rng],
            capture_output=True, text=True, encoding="utf-8", check=True).stdout
    except (subprocess.CalledProcessError, OSError) as e:
        print(f"проверка не отработала: диапазон {rng!r} не разобран — {e}", file=sys.stderr)
        return 2

    records = [(r.split("\x00") + ["", "", "", ""])[:4]
               for r in out.split("\x1e") if r.strip()]
    bad = [r for r in records if r[0].strip() in FORBIDDEN]
    silent = unattributed([(sha, subject, body) for _, sha, subject, body in records])

    if bad:
        print(checks.annotate("error", f"подписано контейнерным умолчанием коммитов: {len(bad)} из {len(records)}"), file=sys.stderr)
        for author, sha, subject, _ in bad:
            print(f"  • {sha} {checks.clip(subject, 60)}\n        автор: {author}", file=sys.stderr)
        print(
            f"\n  Соглашение: автор коммита — владелец, исполнитель уходит трейлером."
            f"\n  Выполните в окне:\n\n      {REMEDY}\n"
            "\n  и перепишите подпись: git commit --amend --reset-author (или новый"
            "\n  коммит поверх). Раньше этого места поймать нечего — хука в облачном"
            "\n  окне нет, и коммит к моменту проверки уже сделан.",
            file=sys.stderr,
        )
        return 1

    if silent:
        print(checks.annotate(
            "error", f"без трейлера исполнителя коммитов: {len(silent)} из {len(records)}"),
            file=sys.stderr)
        for sha, subject in silent:
            print(f"  • {sha} {checks.clip(subject, 60)}", file=sys.stderr)
        print(
            "\n  Общая ветка требует атрибуцию у КАЖДОГО первопредка, и красное там"
            "\n  означает долг: прошлое не переписать (114). Здесь оно ещё чинится —"
            "\n  допишите в сообщение хвостовым блоком:\n"
            f"\n      {TRAILER}\n"
            "\n  и переподпишите: git commit --amend (или новый коммит поверх).",
            file=sys.stderr,
        )
        return 1

    print(f"подписи авторов в порядке: {len(records)} коммитов в {rng}, "
          f"все несут трейлер исполнителя")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
